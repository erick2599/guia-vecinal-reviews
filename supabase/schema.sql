-- Esquema completo para recrear el proyecto de Supabase de GuíaVecinal.
-- Ejecutar en el SQL Editor del proyecto nuevo (dashboard de Supabase).

create table if not exists public.negocios (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nombre text not null,
  categoria text not null,
  slug text,
  descripcion text not null,
  calificacion integer not null check (calificacion between 1 and 5),
  direccion text,
  imagen_prueba_url text,
  es_promocionado boolean not null default false,
  horario text,
  nombre_propietario text,
  telefono_contacto text,
  redes_sociales text,
  dueno_id uuid references auth.users (id) on delete set null,
  respuesta_dueno text
);

create table if not exists public.solicitudes_verificacion (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  nombre_dueno text not null,
  email_contacto text not null,
  nombre_negocio text not null,
  direccion_negocio text,
  mensaje_verificacion text not null
);

create index if not exists negocios_created_at_idx on public.negocios (created_at desc);
create index if not exists negocios_categoria_idx on public.negocios (categoria);
create index if not exists negocios_dueno_id_idx on public.negocios (dueno_id);

alter table public.negocios enable row level security;
alter table public.solicitudes_verificacion enable row level security;

-- Lectura pública de reseñas
drop policy if exists "Lectura publica de negocios" on public.negocios;
create policy "Lectura publica de negocios"
  on public.negocios for select to anon, authenticated
  using (true);

-- Cualquier vecino puede publicar una reseña
drop policy if exists "Publicacion de resenas" on public.negocios;
create policy "Publicacion de resenas"
  on public.negocios for insert to anon, authenticated
  with check (true);

-- Solo el dueño asignado puede responder su reseña
drop policy if exists "Respuesta del dueno" on public.negocios;
create policy "Respuesta del dueno"
  on public.negocios for update to authenticated
  using (auth.uid() = dueno_id)
  with check (auth.uid() = dueno_id);

-- Formulario de verificación de comercios
drop policy if exists "Envio de solicitudes" on public.solicitudes_verificacion;
create policy "Envio de solicitudes"
  on public.solicitudes_verificacion for insert to anon, authenticated
  with check (true);

-- Almacenamiento público de fotografías de reseñas
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'fotos-resenas',
  'fotos-resenas',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp', 'image/gif']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "Fotos resenas lectura publica" on storage.objects;
create policy "Fotos resenas lectura publica"
  on storage.objects for select to public
  using (bucket_id = 'fotos-resenas');

drop policy if exists "Fotos resenas subida publica" on storage.objects;
create policy "Fotos resenas subida publica"
  on storage.objects for insert to public
  with check (bucket_id = 'fotos-resenas');
